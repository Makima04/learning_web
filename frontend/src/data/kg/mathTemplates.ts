const BY_KP = new Map<string, MathTemplate[]>();
const BY_ID = new Map<string, MathTemplate>();
for (const tpl of MATH_TEMPLATES) {
  if (BY_ID.has(tpl.id)) throw new Error(`重复模板 id：${tpl.id}`);
  BY_ID.set(tpl.id, tpl);
  BY_KP.set(tpl.kpId, [...(BY_KP.get(tpl.kpId) ?? []), tpl]);
}

export function templatesForKp(kpId: string): MathTemplate[] {
  return BY_KP.get(kpId) ?? [];
}

export function mathTemplateName(id: string): string {
  return BY_ID.get(id)?.name ?? id;
}

/** 题目在指定考点下命中的模板（一题可命中多类，综合题自然关联多个模板）。 */
export function templateIdsForItem(kpId: string, facets: string[] | undefined): string[] {
  if (!facets?.length) return [];
  return templatesForKp(kpId).filter((tpl) => facets.some((f) => tpl.facets.includes(f))).map((tpl) => tpl.id);
}

