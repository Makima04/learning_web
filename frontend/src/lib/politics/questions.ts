import type { PoliticsQuestion, PoliticsSubject, QuestionPart, ScorePoint } from "./types";
import { SUBJECT_NO } from "./types";

function pt(id: string, score: number, text: string, keywords: string[]): ScorePoint {
  return { id, score, text, keywords };
}

function part(
  id: string,
  prompt: string,
  points: number,
  scorePoints: ScorePoint[],
  materialHints: string[],
  skeleton: string,
  model: string
): QuestionPart {
  return { id, prompt, points, scorePoints, materialHints, skeleton, model };
}

function q(
  year: number,
  subject: PoliticsSubject,
  title: string,
  materials: { label: string; text: string }[],
  parts: QuestionPart[]
): PoliticsQuestion {
  const no = SUBJECT_NO[subject];
  return { id: `${year}-${no}`, year, no, subject, title, materials, parts };
}

