export const POLITICS_YEARS = [2026, 2025, 2024] as const;

export function questionById(id: string): PoliticsQuestion | undefined {
  return POLITICS_QUESTIONS.find((x) => x.id === id);
}

export function questionsOf(year?: number, subject?: PoliticsSubject): PoliticsQuestion[] {
  return POLITICS_QUESTIONS.filter((q0) => {
    if (year && q0.year !== year) return false;
    if (subject && q0.subject !== subject) return false;
    return true;
  });
}
